import { createHash, randomUUID } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, realpath, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { basename, dirname, join } from 'node:path';

import { afterEach, describe, expect, it } from 'vitest';

import {
  bootstrapProjectHome,
  createSpecificationScaffold,
  createSpecificationFromRequest,
  openSpecFlowEngine,
} from '../src/testing';
import { createLegacySpecificationScaffold } from '../src/specs/model';
import {
  fingerprintCreateClientIntent,
  normalizeCreateClientIntent,
} from '../src/specs/create-intent';
import {
  createJournalPath,
  publishCreateJournal,
  readCreateJournal,
  withCreateJournalLock,
  type CreateJournalV1,
  type CreateJournalV2,
} from '../src/specs/create-journal';

const roots: string[] = [];
afterEach(async () => {
  await Promise.all(roots.splice(0).map((root) => rm(root, { recursive: true, force: true })));
});

async function fixture() {
  const root = await realpath(await mkdtemp(join(tmpdir(), 'vc03-journal-Ż ')));
  roots.push(root);
  execFileSync('git', ['init', '-q'], { cwd: root });
  await mkdir(join(root, '.nevo'));
  await writeFile(join(root, '.gitignore'), '.nevo/local/\n');
  await writeFile(join(root, '.nevo/config.yaml'), 'runtime: {}\n');
  execFileSync('git', ['add', '.gitignore', '.nevo/config.yaml'], { cwd: root });
  execFileSync(
    'git',
    ['-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', 'commit', '-qm', 'initial'],
    { cwd: root },
  );
  return (await bootstrapProjectHome(root)).context;
}

/** Structural JSON fixture only; migration test seeds a genuine v1-shaped journal. */
function legacy(context: Awaited<ReturnType<typeof fixture>>): CreateJournalV1 {
  const slug = 'legacy-journal';
  return {
    version: 1,
    operationId: randomUUID(),
    projectId: context.project.projectId,
    inputFingerprint: 'a'.repeat(64),
    specId: randomUUID(),
    slug,
    title: 'Legacy journal',
    created: '2026-10-13',
    stage: 'reserved',
    target: {
      kind: 'existing',
      workspaceId: randomUUID(),
      workspaceRoot: context.project.homeRoot,
    },
    files: [
      { relativePath: 'specs/active/' + slug + '/change.yaml', sha256: 'b'.repeat(64) },
      { relativePath: 'specs/active/' + slug + '/overview.md', sha256: 'c'.repeat(64) },
    ],
  };
}

describe('VC05 — atomic v2 writer with legacy v1 retry', () => {
  it('resumes a pre-cutover v1 journal with original fingerprint, date and binding', async () => {
    const context = await fixture();
    const engine = await openSpecFlowEngine({ cwd: context.project.homeRoot });
    const operationId = randomUUID();
    const specId = randomUUID();
    const created = '2026-10-13';
    const title = 'Authentic legacy retry';
    const target = { kind: 'existing' as const, workspaceId: engine.workspace.workspaceId };
    const scaffold = createLegacySpecificationScaffold({ specId, title, created });
    const legacyFingerprint = createHash('sha256')
      .update(JSON.stringify({ title, created, target }), 'utf8')
      .digest('hex');

    // Persisted, byte-for-byte v1 record format generated by the previous
    // writer's normalized input + durable scaffold, without invoking a new
    // v1 writer after the cutover.
    const record: CreateJournalV1 = {
      version: 1,
      projectId: context.project.projectId,
      operationId,
      inputFingerprint: legacyFingerprint,
      specId,
      slug: scaffold.slug,
      title,
      created,
      stage: 'reserved',
      target: { ...target, workspaceRoot: context.project.homeRoot },
      files: scaffold.files.map(({ relativePath, sha256 }) => ({ relativePath, sha256 })),
    };
    await withCreateJournalLock(context, async () => {
      await writeFile(createJournalPath(context, operationId), JSON.stringify(record) + '\n');
    });
    expect(await readCreateJournal(context, operationId)).toEqual(record);

    const restarted = await openSpecFlowEngine({ cwd: context.project.homeRoot });
    const request = { operationId, title, target };
    const createdResult = await createSpecificationFromRequest(restarted, request);
    expect(createdResult.specId).toBe(specId);
    expect(createdResult.workspaceId).toBe(engine.workspace.workspaceId);
    expect(await createSpecificationFromRequest(restarted, request)).toEqual(createdResult);
    const completed = await readCreateJournal(context, operationId);
    expect(completed?.version).toBe(1);
    expect(completed?.stage).toBe('completed');
    expect(completed?.created).toBe(created);
    expect(completed?.inputFingerprint).toBe(legacyFingerprint);
    expect(
      (await restarted.readRegistry()).specBindings.filter((item) => item.specId === specId),
    ).toHaveLength(1);
    expect(
      await readFile(join(createdResult.workspaceRoot, createdResult.relativeManifestPath), 'utf8'),
    ).toContain(specId);

    await expect(
      createSpecificationFromRequest(restarted, { ...request, title: 'Other legacy intent' }),
    ).rejects.toMatchObject({ code: 'CREATE_CONFLICT' });
  }, 120000);

  it('VC05: replays a pre-cutover v1 worktree with old omitted HEAD semantics', async () => {
    const context = await fixture();
    const root = context.project.homeRoot;
    const title = 'Legacy linked once';
    const created = '2026-10-13';
    const specId = randomUUID();
    const operationId = randomUUID();
    const scaffold = createLegacySpecificationScaffold({ specId, title, created });
    const workspaceId = randomUUID();
    const legacy: CreateJournalV1 = {
      version: 1,
      projectId: context.project.projectId,
      operationId,
      inputFingerprint: createHash('sha256')
        .update(
          JSON.stringify({
            title,
            created,
            target: { kind: 'new-worktree', baseRef: 'HEAD' },
          }),
          'utf8',
        )
        .digest('hex'),
      specId,
      slug: scaffold.slug,
      title,
      created,
      stage: 'reserved',
      target: {
        kind: 'new-worktree',
        workspaceId,
        workspaceRoot: join(dirname(root), basename(root) + '-worktrees', scaffold.slug),
        instanceId: randomUUID(),
        branch: 'spec/' + scaffold.slug + '-' + specId.slice(0, 8),
        baseCommit: execFileSync('git', ['rev-parse', 'HEAD'], {
          cwd: root,
          encoding: 'utf8',
        }).trim(),
      },
      files: scaffold.files.map(({ relativePath, sha256 }) => ({ relativePath, sha256 })),
    };
    await withCreateJournalLock(context, async () => {
      await writeFile(createJournalPath(context, operationId), JSON.stringify(legacy) + '\n');
    });
    await writeFile(
      join(root, '.nevo/config.yaml'),
      'runtime: {}\ngit:\n  enabled: true\n  worktrees:\n    branchPattern: "replacement/{slug}-{shortId}"\n    baseRef: refs/heads/not-created\n',
    );
    const restarted = await openSpecFlowEngine({ cwd: root });
    const omitted = { operationId, title, target: { kind: 'new-worktree' as const } };
    const result = await createSpecificationFromRequest(restarted, omitted);
    roots.push(dirname(result.workspaceRoot));
    expect(result.specId).toBe(specId);
    expect(result.workspaceRoot).toBe(legacy.target.workspaceRoot);
    if (legacy.target.kind !== 'new-worktree') throw new Error('Expected legacy worktree.');
    expect(
      execFileSync('git', ['symbolic-ref', '--short', 'HEAD'], {
        cwd: result.workspaceRoot,
        encoding: 'utf8',
      }).trim(),
    ).toBe(legacy.target.branch);
    expect((await readCreateJournal(context, operationId))?.version).toBe(1);
    expect((await readCreateJournal(context, operationId))?.created).toBe(created);
    expect(
      await createSpecificationFromRequest(restarted, {
        ...omitted,
        target: { kind: 'new-worktree', baseRef: 'HEAD' },
      }),
    ).toEqual(result);
    expect(
      (await restarted.readRegistry()).specBindings.filter((x) => x.specId === specId),
    ).toHaveLength(1);
  }, 120000);


  it('replays a persisted pre-cutover V2 journal with its original legacy manifest SHA', async () => {
    const context = await fixture();
    const engine = await openSpecFlowEngine({ cwd: context.project.homeRoot });
    const operationId = randomUUID();
    const specId = randomUUID();
    const title = 'Pre-cutover V2 replay';
    const created = '2026-10-14';
    const workspaceId = engine.workspace.workspaceId;
    const historical = createLegacySpecificationScaffold({ specId, title, created });
    const intent = normalizeCreateClientIntent({
      title,
      target: { kind: 'existing', workspaceId },
    });
    const record: CreateJournalV2 = {
      version: 2,
      projectId: context.project.projectId,
      operationId,
      inputFingerprint: fingerprintCreateClientIntent(intent),
      specId,
      slug: historical.slug,
      title,
      created,
      stage: 'reserved',
      target: {
        kind: 'existing',
        workspaceId,
        workspaceRoot: context.project.homeRoot,
      },
      files: historical.files.map(({ relativePath, sha256 }) => ({ relativePath, sha256 })),
      requestIntent: intent,
    };
    await withCreateJournalLock(context, async () => {
      await writeFile(createJournalPath(context, operationId), JSON.stringify(record) + '\n');
    });

    const restarted = await openSpecFlowEngine({ cwd: context.project.homeRoot });
    const request = { operationId, title, target: { kind: 'existing' as const, workspaceId } };
    const createdSpec = await createSpecificationFromRequest(restarted, request);
    expect(createdSpec.relativeManifestPath).toBe(historical.files[0]?.relativePath);
    expect(await readFile(join(createdSpec.workspaceRoot, createdSpec.relativeManifestPath), 'utf8'))
      .toBe(historical.files[0]?.content);
    expect(await createSpecificationFromRequest(restarted, request)).toEqual(createdSpec);
    expect((await readCreateJournal(context, operationId))?.version).toBe(2);
    expect((await readCreateJournal(context, operationId))?.files).toEqual(record.files);
  }, 120000);

  it('rejects mixed or unrecognized manifest paths in immutable Create evidence', async () => {
    const context = await fixture();
    const historical = legacy(context);
    const intent = normalizeCreateClientIntent({
      title: historical.title,
      target: { kind: 'existing', workspaceId: historical.target.workspaceId },
    });
    const record: CreateJournalV2 = {
      ...historical,
      version: 2,
      requestIntent: intent,
      inputFingerprint: fingerprintCreateClientIntent(intent),
    };
    await withCreateJournalLock(context, () => Promise.resolve());
    const path = createJournalPath(context, record.operationId);
    const nextScaffold = createSpecificationScaffold({
      specId: record.specId,
      title: record.title,
      created: record.created,
    });
    await writeFile(path, JSON.stringify({ ...record, files: nextScaffold.files.map(
      ({ relativePath, sha256 }) => ({ relativePath, sha256 }),
    ) }) + '\n');
    expect((await readCreateJournal(context, record.operationId))?.files[0]?.relativePath)
      .toBe(nextScaffold.files[0]?.relativePath);

    const mixed = [...record.files];
    mixed[0] = { ...mixed[0], relativePath: 'specs/active/' + record.slug + '/unknown.yaml' };
    await writeFile(path, JSON.stringify({ ...record, files: mixed }) + '\n');
    await expect(readCreateJournal(context, record.operationId)).rejects.toMatchObject({
      code: 'CREATE_JOURNAL_CORRUPT',
    });
  });

  it('round-trips a structural v1 journal fixture without changing its representation', async () => {
    const context = await fixture();
    const item = legacy(context);
    await expect(
      withCreateJournalLock(context, () => publishCreateJournal(context, item)),
    ).rejects.toMatchObject({ code: 'CREATE_RECOVERY_REQUIRED' });
    await withCreateJournalLock(context, async () => {
      await writeFile(createJournalPath(context, item.operationId), JSON.stringify(item) + '\n');
    });
    const raw = await readFile(createJournalPath(context, item.operationId), 'utf8');
    expect(JSON.parse(raw)).toEqual(item);
    expect(await readCreateJournal(context, item.operationId)).toEqual(item);
  });

  it('validates a stored v2 intent independently of Engine-generated created date', async () => {
    const context = await fixture();
    const prior = legacy(context);
    const intent = normalizeCreateClientIntent({
      title: prior.title,
      target: { kind: 'existing', workspaceId: prior.target.workspaceId },
    });
    const next: CreateJournalV2 = {
      ...prior,
      target: {
        kind: 'existing',
        workspaceId: prior.target.workspaceId,
        workspaceRoot: prior.target.workspaceRoot,
      },
      version: 2,
      requestIntent: intent,
      inputFingerprint: fingerprintCreateClientIntent(intent),
      created: '2026-10-14',
    };
    await withCreateJournalLock(context, () => Promise.resolve());
    const file = createJournalPath(context, next.operationId);
    await writeFile(file, JSON.stringify(next) + '\n');
    expect(await readCreateJournal(context, next.operationId)).toEqual(next);
    expect(fingerprintCreateClientIntent(intent)).toBe(next.inputFingerprint);
    await withCreateJournalLock(context, () => publishCreateJournal(context, next));
    expect(await readCreateJournal(context, next.operationId)).toEqual(next);
  });

  it('rejects extra fields in v2 journal targets while preserving v1 readability', async () => {
    const context = await fixture();
    const before = legacy(context);
    const intent = normalizeCreateClientIntent({
      title: before.title,
      target: { kind: 'existing', workspaceId: before.target.workspaceId },
    });
    const record: CreateJournalV2 = {
      ...before,
      version: 2,
      target: {
        kind: 'existing',
        workspaceId: before.target.workspaceId,
        workspaceRoot: before.target.workspaceRoot,
      },
      requestIntent: intent,
      inputFingerprint: fingerprintCreateClientIntent(intent),
    };
    await withCreateJournalLock(context, () => Promise.resolve());
    const path = createJournalPath(context, record.operationId);
    await writeFile(path, JSON.stringify(record) + '\n');
    expect(await readCreateJournal(context, record.operationId)).toEqual(record);

    for (const extra of [
      { instanceId: randomUUID() },
      { branch: 'unexpected' },
      { baseCommit: 'a'.repeat(40) },
      { unexpected: true },
    ]) {
      await writeFile(path, JSON.stringify({ ...record, target: { ...record.target, ...extra } }));
      await expect(readCreateJournal(context, record.operationId)).rejects.toMatchObject({
        code: 'CREATE_JOURNAL_CORRUPT',
      });
    }

    const worktreeIntent = normalizeCreateClientIntent({
      title: before.title,
      target: { kind: 'new-worktree' },
    });
    const worktreeRecord: CreateJournalV2 = {
      ...record,
      requestIntent: worktreeIntent,
      inputFingerprint: fingerprintCreateClientIntent(worktreeIntent),
      target: {
        kind: 'new-worktree',
        workspaceId: randomUUID(),
        workspaceRoot: join(dirname(context.project.homeRoot), 'reserved-worktree'),
        branch: 'spec/reserved-12345678',
        baseCommit: 'a'.repeat(40),
        instanceId: randomUUID(),
      },
      gitPlan: {
        projectRoot: context.project.homeRoot,
        gitInstanceId: context.project.gitInstanceId,
      },
    };
    await writeFile(
      path,
      JSON.stringify({ ...worktreeRecord, target: { ...worktreeRecord.target, unexpected: true } }),
    );
    await expect(readCreateJournal(context, record.operationId)).rejects.toMatchObject({
      code: 'CREATE_JOURNAL_CORRUPT',
    });

    // Existing V1 journals may have legacy extra target properties.
    await writeFile(
      path,
      JSON.stringify({ ...before, target: { ...before.target, branch: 'legacy-extra' } }),
    );
    await expect(readCreateJournal(context, before.operationId)).resolves.toMatchObject({
      version: 1,
      target: { branch: 'legacy-extra' },
    });
  });

  it('distinguishes omitted and explicit baseRef even when both would target HEAD', () => {
    const base = { title: 'Same intent' };
    const omitted = normalizeCreateClientIntent({ ...base, target: { kind: 'new-worktree' } });
    const explicit = normalizeCreateClientIntent({
      ...base,
      target: { kind: 'new-worktree', baseRef: 'HEAD' },
    });
    expect(fingerprintCreateClientIntent(omitted)).not.toBe(
      fingerprintCreateClientIntent(explicit),
    );
    expect(fingerprintCreateClientIntent(omitted)).toBe(
      fingerprintCreateClientIntent(
        normalizeCreateClientIntent({
          ...base,
          target: { kind: 'new-worktree' },
        }),
      ),
    );
  });

  it('rejects tampered v2 fingerprint or Git plan identity', async () => {
    const context = await fixture();
    const before = legacy(context);
    const intent = normalizeCreateClientIntent({
      title: before.title,
      target: { kind: 'new-worktree' },
    });
    const next: CreateJournalV2 = {
      ...before,
      version: 2,
      requestIntent: intent,
      inputFingerprint: fingerprintCreateClientIntent(intent),
      target: {
        kind: 'new-worktree',
        workspaceId: before.target.workspaceId,
        workspaceRoot: before.target.workspaceRoot,
        branch: 'feature/legacy-12345678',
        baseCommit: 'a'.repeat(40),
        instanceId: randomUUID(),
      },
      gitPlan: {
        projectRoot: context.project.homeRoot,
        gitInstanceId: context.project.gitInstanceId,
      },
    };
    await withCreateJournalLock(context, () => Promise.resolve());
    const path = createJournalPath(context, next.operationId);
    await writeFile(path, JSON.stringify(next));
    expect(await readCreateJournal(context, next.operationId)).toEqual(next);
    await writeFile(path, JSON.stringify({ ...next, inputFingerprint: 'f'.repeat(64) }));
    await expect(readCreateJournal(context, next.operationId)).rejects.toMatchObject({
      code: 'CREATE_JOURNAL_CORRUPT',
    });
    await writeFile(
      path,
      JSON.stringify({ ...next, gitPlan: { ...next.gitPlan, gitInstanceId: randomUUID() } }),
    );
    await expect(readCreateJournal(context, next.operationId)).rejects.toMatchObject({
      code: 'CREATE_JOURNAL_CORRUPT',
    });
  });
});
